  <h1> Strategic Supply Chain Leadership and Financial Acumen </h1>
  <h4>Short Course Description (for Catalogs or Listings)</h4>
  <p>This course prepares students to lead modern supply chain operations with strategic insight, leadership skill, and
    financial acumen. Students will explore key CPIM certification concepts, apply decision-making in the FLEX simulation,
    and develop people-centered leadership behaviors. The course emphasizes operational alignment, risk management, and
    continuous improvement in dynamic environments.</p>

  <h4>Full Course Description</h4>
  <p>This 40-hour course offers a strategic and applied education in supply chain management, combining APICS CPIM
    certification content, leadership soft skills, and financial literacy through an experiential simulation. Students
    will run a simulated company using the FLEXEE simulation, applying decision-making across demand, sourcing,
    production, logistics, and finance. Each module blends textbook learning, simulation actions, leadership development,
    and CPIM-aligned insights.</p>

  <h4>Key Competencies and Skills Developed</h4>
  <ul>
    <li>- Strategic Supply Chain Planning and Execution (CPIM-aligned)</li>
    <li>- Leadership Skills: Vision, Communication, Risk Management, Conflict Resolution</li>
    <li>- Financial Literacy: P&L, Cost Structures, Margin Management, Investment Decisions</li>
    <li>- Simulation-based Learning: Integrated Decision-Making Across SCM Functions</li>
    <li>- CPIM Domain Familiarity: Demand Planning, S&OP, Inventory, Procurement, and Continuous Improvement</li>
  </ul>

  <h4>Target Audience</h4>
  <ul>
    <li>- University students in Supply Chain, Business, or Operations majors</li>
    <li>- Professionals preparing for the CPIM certification exam</li>
    <li>- Emerging leaders in corporate supply chain roles</li>
    <li>- Corporate trainees in leadership and operational roles</li>
  </ul>

  <h4>Prerequisites</h4>
  <p>No formal prerequisites required. Prior exposure to business or operations concepts is helpful but not required.</p>



