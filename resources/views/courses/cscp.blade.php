  <h1>Strategic Supply Chain Leadership and Financial Acumen (CSCP Integrated)</h1>
  <h4>Short Course Description (for Catalogs or Listings)</h4>
  <p>This course prepares students to lead global supply chain operations with strategic insight, leadership skills, and
    financial acumen. Students will explore key CSCP certification concepts, apply decision-making in the FLEX simulation,
    and develop people-centered leadership behaviors. The course emphasizes global operations, risk management, end-to-end
    supply chain integration, and continuous improvement in dynamic environments.</p>
  <h4>Full Course Description</h4>
  <p>This 40-hour course offers a strategic and applied education in global supply chain management, combining APICS CSCP
    certification content, leadership soft skills, and financial literacy through experiential simulation. Students will
    run a simulated company using the FLEX simulation, applying decision-making across sourcing, planning, manufacturing,
    logistics, and compliance. Each module blends textbook learning, simulation actions, leadership development, and
    CSCP-aligned insights designed for future supply chain leaders.</p>
  <h4>Key Competencies and Skills Developed</h4>
  <ul>
    <li>- Strategic Global Supply Chain Planning and Execution (CSCP-aligned)</li>
    <li>- Leadership Skills: Vision, Global Thinking, Risk Management, Ethics</li>
    <li>- Financial Literacy: Total Cost of Ownership, Margin Management, Working Capital</li>
    <li>- Simulation-based Learning: Integrated Decision-Making Across Supply Chain Functions</li>
    <li>- CSCP Domain Familiarity: Design, Planning & Execution, and Improvement & Compliance</li>
  </ul>
  <h4>Target Audience</h4>
  <ul>
    <li>- University students in Supply Chain, Business, or Global Operations majors
      - Professionals preparing for the CSCP certification exam
      - Emerging leaders in international or multi-enterprise supply chain roles
      - Corporate trainees in global supply chain leadership pipelines</li>
  </ul>
  <h4>Prerequisites</h4>
  <p>No formal prerequisites required. Prior exposure to business or operations concepts is helpful but not required.</p>
